public class Filme {
    String titulo;
    String diretor;
    int ano;
    int duracaoMinutos;

    public Filme(String titulo, String diretor, int ano, int duracaoMinutos) {
        this.titulo = titulo;
        this.diretor = diretor;
        this.ano = ano;
        this.duracaoMinutos = duracaoMinutos;
    }
}